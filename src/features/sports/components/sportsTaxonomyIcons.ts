/** Resolves a taxonomy slug to a public icon, falling back to its parent icon. */
export function resolveSportsTaxonomyIcon(
  slug: string,
  parentIcon?: string,
): string | undefined {
  const normalizedSlug = slug.trim().toLowerCase().replaceAll("_", "-");
  const exactIcon = EXACT_ICON_BY_SLUG[normalizedSlug];
  if (exactIcon) return `${TAXONOMY_ICON_ROOT}/${exactIcon}`;

  const matchingRule = ICON_RULES.find(([pattern]) =>
    pattern.test(normalizedSlug),
  );
  return matchingRule ? `${TAXONOMY_ICON_ROOT}/${matchingRule[1]}` : parentIcon;
}
